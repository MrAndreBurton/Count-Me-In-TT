create table public.game_results (
"id" uuid not null default gen_random_uuid(),
"student_id" uuid not null,
"account_id" uuid not null,
"game_type" text not null,
"game_mode" text not null,
"mode_label" text not null,
"duration_ms" integer,
"score" integer,
"max_score" integer,
"correct_answers" integer,
"incorrect_answers" integer,
"accuracy_percent" numeric(5,2),
"submission_type" text not null default 'practice'::text,
"challenge_key" text,
"event_name" text,
"public_eligible" boolean not null default true,
"verification_status" text not null default 'pending'::text,
"anti_cheat_data" jsonb not null default '{}'::jsonb,
"rejection_reason" text,
"is_personal_best" boolean not null default false,
"played_at" timestamp with time zone not null default now(),
"created_at" timestamp with time zone not null default now(),
"updated_at" timestamp with time zone not null default now(),
"content_release_id" text,
"symbol_bank_release_id" text,
"game_metadata" jsonb not null default '{}'::jsonb,
"context_type" text not null default 'personal'::text,
"organisation_id" uuid,
"group_id" uuid,
 primary key(id),
 check ((correct_answers is null) or (incorrect_answers is null) or (max_score is null) or (correct_answers+incorrect_answers<=max_score)),
 check (duration_ms is null or duration_ms>=0),
 check (accuracy_percent is null or accuracy_percent between 0 and 100),
 check (jsonb_typeof(game_metadata)='object'),
 check (context_type in ('personal','organisation')),
 check ((context_type='personal' and organisation_id is null and group_id is null) or (context_type='organisation' and organisation_id is not null))
);

